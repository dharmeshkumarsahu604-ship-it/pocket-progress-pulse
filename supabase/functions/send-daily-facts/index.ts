// Get today's fact based on day of year
function getTodaysFact(): typeof geologyFacts[0] {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  return geologyFacts[dayOfYear % geologyFacts.length];
}

serve(async (req) => {
  // Handle CORS preflight
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const supabaseUrl = Deno.env.get('SUPABASE_URL')!;
    const supabaseServiceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!;
    const vapidPublicKey = Deno.env.get('VAPID_PUBLIC_KEY');
    const vapidPrivateKey = Deno.env.get('VAPID_PRIVATE_KEY');
    const vapidSubject = Deno.env.get('VAPID_SUBJECT');

    if (!vapidPublicKey || !vapidPrivateKey || !vapidSubject) {
      console.error('VAPID keys not configured');
      return new Response(
        JSON.stringify({ error: 'Push notifications not configured' }),
        { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const supabase = createClient(supabaseUrl, supabaseServiceKey);
    
    // Get current hour (UTC)
    const now = new Date();
    const currentHour = now.getUTCHours();
    const currentHourString = `${currentHour.toString().padStart(2, '0')}:00:00`;
    
    console.log(`Running daily facts job at ${now.toISOString()}, looking for users with preferred time ${currentHourString}`);

    // Get all subscriptions with daily facts enabled and matching preferred time
    const { data: subscriptions, error: subError } = await supabase
      .from('push_subscriptions')
      .select('*')
      .eq('daily_facts_enabled', true)
      .eq('preferred_time', currentHourString);

    if (subError) {
      console.error('Error fetching subscriptions:', subError);
      throw subError;
    }

    if (!subscriptions || subscriptions.length === 0) {
      console.log('No subscriptions found for this time slot');
      return new Response(
        JSON.stringify({ success: true, sent: 0, message: 'No subscriptions for this time' }),
        { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    console.log(`Found ${subscriptions.length} subscriptions to notify`);

    // Get today's fact
    const todaysFact = getTodaysFact();
    console.log(`Today's fact: ${todaysFact.title}`);

    // Call the send-push-notification function
    const { data: pushResult, error: pushError } = await supabase.functions.invoke('send-push-notification', {
      body: {
        userIds: subscriptions.map(s => s.user_id),
        type: 'daily_fact',
        payload: {
          title: `🪨 ${todaysFact.title}`,
          body: todaysFact.body,
          icon: '/favicon.ico',
          badge: '/favicon.ico',
          tag: 'daily-geology-fact',
          data: {
            type: 'daily_fact',
            url: '/'
          }
        }
      }
    });

    if (pushError) {
      console.error('Error sending push notifications:', pushError);
      throw pushError;
    }

    console.log('Push notification result:', pushResult);

    return new Response(
      JSON.stringify({ 
        success: true, 
        fact: todaysFact.title,
        ...pushResult 
      }),
      { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    );

  } catch (error) {
    console.error('Error in send-daily-facts:', error);
    const errorMessage = error instanceof Error ? error.message : 'Unknown error';
    return new Response(
      JSON.stringify({ error: errorMessage }),
      { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    );
  }
});
